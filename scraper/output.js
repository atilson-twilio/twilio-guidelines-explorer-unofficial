// Writes the dataset files shared by `npm run scrape` and `npm run weather`. Two sets:
//
// PUBLIC (committed and published; guideline pages only, never any Weather Report data):
//   data/guidelines.json  the normalized dataset
//   data/changelog.json   cell-level changes detected on each run (most recent first)
//   ui/data.js            the dataset + recent changes, loaded by ui/index.html
//
// LOCAL (gitignored; only written when weather-report-data/ has CSVs):
//   data/local/guidelines.json, data/local/changelog.json  as above, with the Weather Report merged
//   ui/data.local.js      loaded after ui/data.js, replacing it

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { diff } from "./normalize.js";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const WEATHER_DIR = path.join(ROOT, "weather-report-data");
export const PUBLIC = {
  dataJson: path.join(ROOT, "data", "guidelines.json"),
  changelogJson: path.join(ROOT, "data", "changelog.json"),
  uiDataJs: path.join(ROOT, "ui", "data.js"),
};
export const LOCAL = {
  dataJson: path.join(ROOT, "data", "local", "guidelines.json"),
  changelogJson: path.join(ROOT, "data", "local", "changelog.json"),
  uiDataJs: path.join(ROOT, "ui", "data.local.js"),
};
const CHANGELOG_RUNS_KEPT = 52;
const CHANGELOG_RUNS_IN_UI = 8;
const COL_DERIVED = /^wr\.check\./;

export const readJson = (file, fallback) => (fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : fallback);

export function writeFile(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

/** Record changes since `prev` in the changelog and write one set of output files. Returns the changes. */
export function writeOutputs(prev, next, files = PUBLIC) {
  // Columns new in this run (e.g. the first Weather Report merge) aren't "changes", and the
  // derived cross-check column would only repeat changes already recorded for its inputs.
  const known = new Set(prev?.columns.map((c) => c.id));
  const changes = diff(prev, next).filter((ch) => ch.column === "*" || (known.has(ch.column) && !COL_DERIVED.test(ch.column)));
  // A new local changelog starts from the public one, so the guideline history carries over.
  const changelog = readJson(files.changelogJson, files === LOCAL ? readJson(PUBLIC.changelogJson, []) : []);
  if (prev && changes.length) {
    changelog.unshift({ date: new Date().toISOString(), previous: prev.generatedAt, changes });
    changelog.length = Math.min(changelog.length, CHANGELOG_RUNS_KEPT);
  }
  writeFile(files.dataJson, JSON.stringify(next, null, 1) + "\n");
  writeFile(files.changelogJson, JSON.stringify(changelog, null, 1) + "\n");
  const uiPayload = { ...next, changelog: changelog.slice(0, CHANGELOG_RUNS_IN_UI) };
  writeFile(
    files.uiDataJs,
    `// Generated by \`npm run ${files === LOCAL ? "weather" : "scrape"}\` — do not edit by hand.\n` +
      (files === LOCAL ? "// Contains Weather Report data: keep it local, never commit or publish it.\n" : "") +
      `window.GUIDELINES = ${JSON.stringify(uiPayload)};\n`,
  );
  return changes;
}

/** Delete the local files, so stale Weather Report data can't mask newer guideline data. */
export function removeLocalOutputs() {
  for (const file of Object.values(LOCAL)) fs.rmSync(file, { force: true });
}
